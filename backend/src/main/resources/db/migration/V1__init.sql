-- Toucan C&S and Accounting monitor schema. Portable between PostgreSQL and H2 (MODE=PostgreSQL).

CREATE TABLE monitor_run (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_type        VARCHAR(20)  NOT NULL,
    groups_csv          VARCHAR(200) NOT NULL,
    window_from         DATE         NOT NULL,
    window_to           DATE         NOT NULL,
    started_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at         TIMESTAMP WITH TIME ZONE,
    status              VARCHAR(40)  NOT NULL,
    records_collected   INT,
    checks_passed       INT,
    checks_failed       INT,
    checks_not_evaluated INT,
    error               TEXT,
    triggered_by        VARCHAR(100)
);

CREATE TABLE dataset_snapshot (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT       NOT NULL REFERENCES monitor_run (id),
    dataset         VARCHAR(80)  NOT NULL,
    system_name     VARCHAR(20)  NOT NULL,
    endpoint        VARCHAR(300) NOT NULL,
    request_params  TEXT,
    ok              BOOLEAN      NOT NULL,
    error           TEXT,
    record_count    INT          NOT NULL,
    total_reported  BIGINT,
    truncated       BOOLEAN      NOT NULL,
    retrieved_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_snapshot_dataset ON dataset_snapshot (dataset, retrieved_at);
CREATE INDEX ix_snapshot_run ON dataset_snapshot (run_id);

CREATE TABLE source_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset         VARCHAR(80)   NOT NULL,
    system_name     VARCHAR(20)   NOT NULL,
    endpoint        VARCHAR(300)  NOT NULL,
    natural_key     VARCHAR(2000) NOT NULL,
    content_hash    VARCHAR(64)   NOT NULL,
    payload         TEXT          NOT NULL,
    request_params  TEXT,
    first_seen_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    retrieved_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_run_id     BIGINT,
    CONSTRAINT uq_source_record UNIQUE (dataset, natural_key)
);
CREATE INDEX ix_source_record_run ON source_record (dataset, last_run_id);

CREATE TABLE source_record_history (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_record_id BIGINT      NOT NULL REFERENCES source_record (id),
    content_hash     VARCHAR(64) NOT NULL,
    payload          TEXT        NOT NULL,
    retrieved_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    run_id           BIGINT
);
CREATE INDEX ix_history_record ON source_record_history (source_record_id);

-- Typed projection of C&S transactions for filtering and KPIs.
CREATE TABLE cs_txn (
    source_record_id       BIGINT PRIMARY KEY REFERENCES source_record (id),
    natural_key            VARCHAR(2000) NOT NULL,
    rrn                    VARCHAR(64),
    arn                    VARCHAR(64),
    invoice_number         VARCHAR(64),
    merchant_number        VARCHAR(64),
    merchant_name          VARCHAR(300),
    terminal_number        VARCHAR(64),
    run_number             VARCHAR(64),
    scheme_code            VARCHAR(40),
    platform_type          VARCHAR(40),
    transaction_code       VARCHAR(60),
    settlement_status      VARCHAR(40),
    life_cycle_status      VARCHAR(40),
    transaction_status     VARCHAR(40),
    txn_status             VARCHAR(40),
    payment_release_status VARCHAR(40),
    db_or_cr               VARCHAR(10),
    txn_amount             NUMERIC(20, 4),
    net_amount             NUMERIC(20, 4),
    sales_date_time        VARCHAR(40),
    sales_date             DATE,
    accounting_status      VARCHAR(20),
    accounting_checked_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_txn_date ON cs_txn (sales_date);
CREATE INDEX ix_txn_rrn ON cs_txn (rrn);
CREATE INDEX ix_txn_arn ON cs_txn (arn);
CREATE INDEX ix_txn_run ON cs_txn (run_number, merchant_number);
CREATE INDEX ix_txn_platform ON cs_txn (platform_type, sales_date);

CREATE TABLE rule_result (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        BIGINT        NOT NULL REFERENCES monitor_run (id),
    rule_id       VARCHAR(10)   NOT NULL,
    rule_name     VARCHAR(200)  NOT NULL,
    category      VARCHAR(40)   NOT NULL,
    subject_key   VARCHAR(2000) NOT NULL,
    outcome       VARCHAR(20)   NOT NULL,
    message       TEXT,
    processor     VARCHAR(40),
    business_date DATE,
    tt_code       VARCHAR(60),
    ledger        VARCHAR(300),
    evidence      TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_result_run_rule ON rule_result (run_id, rule_id);
CREATE INDEX ix_result_outcome ON rule_result (outcome);

CREATE TABLE tt_mapping (
    code              VARCHAR(60) PRIMARY KEY,
    name              VARCHAR(300),
    gl_lines          TEXT        NOT NULL,
    status            VARCHAR(20) NOT NULL,
    source_record_key VARCHAR(2000),
    source_hash       VARCHAR(64),
    retrieved_at      TIMESTAMP WITH TIME ZONE,
    confirmed_by      VARCHAR(100),
    confirmed_at      TIMESTAMP WITH TIME ZONE,
    note              TEXT
);

CREATE TABLE api_call (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id               BIGINT,
    at                   TIMESTAMP WITH TIME ZONE NOT NULL,
    system_name          VARCHAR(20)  NOT NULL,
    method               VARCHAR(10)  NOT NULL,
    path                 VARCHAR(500) NOT NULL,
    http_status          INT,
    envelope_success     BOOLEAN,
    envelope_status_code INT,
    duration_ms          BIGINT,
    blocked              BOOLEAN NOT NULL,
    error                TEXT
);
CREATE INDEX ix_api_call_run ON api_call (run_id);

CREATE TABLE audit_log (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at       TIMESTAMP WITH TIME ZONE NOT NULL,
    username VARCHAR(100) NOT NULL,
    action   VARCHAR(60)  NOT NULL,
    details  TEXT
);

-- Processors are discovered from platformType values, never hardcoded.
CREATE TABLE processor_config (
    code          VARCHAR(40) PRIMARY KEY,
    display_name  VARCHAR(100) NOT NULL,
    active        BOOLEAN      NOT NULL,
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL
);
